"""What this plugin means when it says which files are its language's.

A project that names no ``files`` of its own scans what its plugins declare, and
``habit-hooks init`` writes exactly such a config — so what is declared here *is*
the first run for anyone who let init set them up. Declared as a bare
``**/*.ts``, that first run reached into ``node_modules`` and reported twenty-odd
thousand smells in other people's packages, which is the same as reporting
nothing: no one reads it, and the project's own eight findings are lost in it.

A dependency is never the project's source, at the top level or vendored beside a
package in a monorepo, so the declaration says so.
"""

from __future__ import annotations

import tomllib
from pathlib import Path

import pathspec

PACKAGE = Path(__file__).resolve().parents[1] / "src" / "habit_hooks_typescript"

PROJECT_SOURCE = ("src/billing.ts", "src/app.tsx", "packages/api/src/handler.ts")
DEPENDENCIES = (
    "node_modules/left-pad/index.ts",
    "node_modules/@types/node/index.d.ts",
    "packages/api/node_modules/lodash/index.ts",
)


def _declared_files() -> pathspec.PathSpec:
    config = tomllib.loads((PACKAGE / "config.toml").read_text(encoding="utf-8"))
    return pathspec.PathSpec.from_lines("gitignore", config["files"])


def test_the_project_s_own_typescript_is_source() -> None:
    spec = _declared_files()

    assert [path for path in PROJECT_SOURCE if spec.match_file(path)] == list(
        PROJECT_SOURCE
    )


def test_an_installed_dependency_is_not_this_project_s_source() -> None:
    """Including one vendored under a package, which a monorepo has one of each."""
    spec = _declared_files()

    assert [path for path in DEPENDENCIES if spec.match_file(path)] == []
